// APESpace Verify: two independent parts.
//
// 1. Code check (always on, read-only). On the meeting sites in config.json, every
//    script, WebAssembly module and stylesheet a tab loads is fingerprinted and
//    compared with the signed release whose app bundle the tab loaded. The badge
//    shows the result: ✓ all match a signed release, ! something does not.
//
//    MV3 extensions cannot read response bodies, so each file is downloaded again
//    and hashed. A server that wanted to deceive the check would have to tell the
//    extension's request apart from the page's and answer it differently.
//
// 2. E2EE Inspector (off by default, test meetings). While switched on, the hook in
//    inspector/ records what this browser receives before decryption and the keys
//    it receives, and searches everything leaving the page for those keys. The
//    HTTP part of that search runs here; it covers requests to the meeting site,
//    or to every site if the user grants access to all sites.

import './inspector/leak-scan.js';
import { releaseLoader, sha256Hex } from './lib/releases.js';

// The meeting sites are the extension's host permissions (manifest.json).
const MATCHES = chrome.runtime.getManifest().host_permissions.filter(m => m !== '<all_urls>');
const ORIGINS = MATCHES.map(m => m.replace(/\/\*$/, ''));
const ALL_SITES = { origins: [ '<all_urls>' ] };

// ------------------------------------------------------------ 1. code check

const CHECKED = /\.(css|js|mjs|wasm)$/;

// Generated by each server for its own deployment, not part of a release.
const GENERATED = [ '/config.js', '/interface_config.js' ];

// Releases whose pages are static files read their settings with this loader;
// in earlier releases the web server assembled each page, so pages can't be
// compared with them.
const STATIC_PAGES_MARKER = '/static/load-config.js';

// The release file a page URL is served from: a file's own path, else the
// meeting page (every room name is served index.html).
const pagePath = pathname => (/\.html$/.test(pathname) ? pathname : '/index.html');
const BADGE = { ok: [ '✓', '#1a7f4b' ], fail: [ '!', '#b42318' ], pending: [ '…', '#6e6e68' ] };

const configPromise = fetch(chrome.runtime.getURL('config.json')).then(r => r.json());
let loader;

const tabKey = tabId => `code:${tabId}`;
const getTab = async tabId => (await chrome.storage.session.get(tabKey(tabId)))[tabKey(tabId)];

async function evaluate(state) {
    const config = await configPromise;

    loader ??= releaseLoader(config);
    const bundle = state.files.find(f => f.path === '/libs/app.bundle.min.js' && f.actual);
    let release = null;

    if (bundle) {
        try {
            release = await loader.find(bundle.path, bundle.actual);
        } catch (e) {
            loader = undefined; // retry next time

            return { verdict: 'pending', error: `Could not load the published releases: ${e.message}` };
        }
    }
    for (const f of state.files) {
        f.status = f.type === 'page' && release && !release.files[STATIC_PAGES_MARKER] ? 'server-assembled'
            : f.actual === undefined ? 'pending'
            : f.actual === null ? 'error'
                : !release ? 'pending'
                    : release.files[f.path]?.sha256 === f.actual ? 'ok'
                        : release.files[f.path] ? 'mismatch' : 'unpublished';
    }

    const bad = state.files.some(f => [ 'mismatch', 'unpublished', 'error' ].includes(f.status));
    const done = state.files.every(f => f.status !== 'pending');

    return {
        verdict: bundle && !release ? 'fail' : bad || (release && !release.signed) ? 'fail'
            : release && done ? 'ok' : 'pending',
        release: release && { id: release.id, signed: release.signed, builds: release.builds },
        unknownBundle: Boolean(bundle && !release)
    };
}

// Updates are serialized per tab, so parallel downloads don't overwrite each other.
const queues = new Map();

function updateTab(tabId, change) {
    const next = (queues.get(tabId) ?? Promise.resolve()).then(async () => {
        const state = await getTab(tabId) ?? { files: [] };

        change(state);
        Object.assign(state, await evaluate(state));
        await chrome.storage.session.set({ [tabKey(tabId)]: state });
        const [ text, color ] = BADGE[state.verdict];

        await chrome.action.setBadgeText({ tabId, text });
        await chrome.action.setBadgeBackgroundColor({ tabId, color });
    });

    queues.set(tabId, next.catch(() => {}));

    return next;
}

async function checkFile(tabId, url, path) {
    let actual = null;

    try {
        const res = await fetch(url, { cache: 'no-store' });

        actual = res.ok ? await sha256Hex(await res.arrayBuffer()) : null;
    } catch {}
    await updateTab(tabId, state => {
        const f = state.files.find(x => x.path === path && x.actual === undefined);

        f && (f.actual = actual);
    });
}

// A new page in the tab: forget the previous page's results. A meeting page,
// in the tab or in an iframe (embedded meeting), is checked like any file.
chrome.webNavigation.onCommitted.addListener(({ tabId, frameId, url }) => {
    if (frameId === 0) {
        queues.set(tabId, (queues.get(tabId) ?? Promise.resolve()).then(async () => {
            await chrome.storage.session.remove(tabKey(tabId));
            await chrome.action.setBadgeText({ tabId, text: '' });
        }).catch(() => {}));
    }
    const page = URL.canParse(url) && new URL(url);

    if (!page || !ORIGINS.includes(page.origin)) {
        return;
    }
    const path = pagePath(page.pathname);

    updateTab(tabId, state => {
        state.origin ??= page.origin;
        state.files.some(f => f.path === path) || state.files.push({ path, type: 'page' });
    }).then(() => checkFile(tabId, url, path));
});

// Every script, WebAssembly module and stylesheet loaded from a meeting site, by
// the page, its iframes (embedded meetings) or its workers.
chrome.webRequest.onCompleted.addListener(details => {
    const url = new URL(details.url);
    const path = url.pathname;

    if (details.tabId < 0 || !ORIGINS.includes(url.origin) || !CHECKED.test(path) || GENERATED.includes(path)) {
        return;
    }
    updateTab(details.tabId, state => {
        state.origin ??= url.origin;
        state.files.some(f => f.path === path) || state.files.push({ path, type: details.type });
    }).then(() => checkFile(details.tabId, details.url, path));
}, { urls: MATCHES });

chrome.tabs.onRemoved.addListener(tabId => chrome.storage.session.remove(tabKey(tabId)));

// ------------------------------------------------------------ 2. E2EE Inspector

const HOOK_ID = 'e2ee-inspector-hook';
const BRIDGE_ID = 'e2ee-inspector-bridge';

async function isOn() {
    return (await chrome.scripting.getRegisteredContentScripts({ ids: [ HOOK_ID ] })).length > 0;
}

// The page hook is registered only while Inspector mode is on, and the
// registration does not survive a browser restart.
async function setOn(on) {
    if (on && !await isOn()) {
        const common = { matches: MATCHES, runAt: 'document_start', allFrames: true, persistAcrossSessions: false };

        await chrome.scripting.registerContentScripts([
            { id: HOOK_ID, js: [ 'inspector/leak-scan.js', 'inspector/hook.js' ], world: 'MAIN', ...common },
            { id: BRIDGE_ID, js: [ 'inspector/bridge.js' ], world: 'ISOLATED', ...common }
        ]);
    } else if (!on && await isOn()) {
        await chrome.scripting.unregisterContentScripts({ ids: [ HOOK_ID, BRIDGE_ID ] });
        await chrome.permissions.remove(ALL_SITES).catch(() => {});
    }
    await chrome.action.setTitle({ title: `APESpace Verify (E2EE Inspector ${on ? 'ON' : 'off'})` });

    return on;
}

const inspectorStatus = async () => ({
    on: await isOn(),
    allSites: await chrome.permissions.contains(ALL_SITES),
    origins: ORIGINS
});

// HTTP leak check: requests from tabs running the hook (their iframes and workers
// carry the tab's id; service-worker requests carry -1 and are checked against
// every inspected tab). Chrome only reports requests to sites the extension may
// access: the meeting sites, or every site once the user allows it.
const LEAK_WINDOW_MS = 120000;
const tabs = new Map(); // tabId -> { keys, scanned, bytes, findings, recent }

const tabState = id => {
    if (!tabs.has(id)) {
        tabs.set(id, { keys: [], scanned: 0, bytes: 0, findings: [], recent: [] });
    }

    return tabs.get(id);
};
const keyId = k => `${k.participantId}:${k.keyIndex}:${k.key.join(',')}`;

function scanRequest(st, req, keys) {
    for (const payload of req.payloads) {
        for (const hit of globalThis.E2EELeakScan.scan(payload, keys)) {
            st.findings.push({ t: req.t, channel: req.channel, destination: req.destination,
                requestType: req.requestType, initiator: req.initiator, ...hit });
        }
    }
}

chrome.webRequest.onBeforeRequest.addListener(details => {
    const targets = details.tabId >= 0 ? (tabs.has(details.tabId) ? [ details.tabId ] : []) : [ ...tabs.keys() ];

    if (!targets.length) {
        return;
    }
    const payloads = [ details.url ];

    for (const part of details.requestBody?.raw ?? []) {
        part.bytes && payloads.push(part.bytes);
    }
    if (details.requestBody?.formData) {
        payloads.push(JSON.stringify(details.requestBody.formData));
    }
    const url = new URL(details.url);
    const req = {
        t: Math.round(details.timeStamp),
        channel: details.tabId >= 0 ? 'http' : 'http (service worker)',
        destination: `${details.method} ${url.origin}${url.pathname}`.slice(0, 200),
        requestType: details.type,
        initiator: details.initiator ?? null,
        payloads
    };

    for (const id of targets) {
        const st = tabState(id);

        st.scanned++;
        st.bytes += payloads.reduce((n, p) => n + (typeof p === 'string' ? p.length : p.byteLength), 0);
        scanRequest(st, req, st.keys);
        st.recent.push(req);
        while (st.recent.length && st.recent[0].t < req.t - LEAK_WINDOW_MS) {
            st.recent.shift();
        }
    }
}, { urls: [ '<all_urls>' ] }, [ 'requestBody' ]);

chrome.tabs.onRemoved.addListener(id => tabs.delete(id));
chrome.runtime.onStartup.addListener(() => setOn(false));

// ------------------------------------------------------------ messages

chrome.runtime.onMessage.addListener((msg, sender, reply) => {
    switch (msg.type) {
    case 'leak-status': {
        const st = tabState(sender.tab?.id ?? -1);
        const known = new Set(st.keys.map(keyId));
        const fresh = msg.keys.filter(k => k.key && !known.has(keyId(k)));

        // Requests sent before a key was known are checked again with it.
        for (const req of st.recent) {
            scanRequest(st, req, fresh);
        }
        st.keys.push(...fresh);
        chrome.permissions.contains(ALL_SITES).then(all => reply({
            scanned: st.scanned, bytes: st.bytes, findings: st.findings,
            scope: all ? 'all sites' : 'the meeting site only'
        }));

        return true;
    }
    case 'code-status':
        getTab(msg.tabId).then(reply);

        return true;
    case 'set':
        setOn(msg.on).then(inspectorStatus).then(reply);

        return true;
    case 'get':
        inspectorStatus().then(reply);

        return true;
    }
});
