const $ = id => document.getElementById(id);
const el = (tag, cls, text) => Object.assign(document.createElement(tag), cls ? { className: cls } : {}, { textContent: text ?? '' });
const ALL_SITES = { origins: [ '<all_urls>' ] };

// ------------------------------------------------------------ code check

function showCode(state, origins) {
    const box = $('code');

    if (!state) {
        box.append(el('p', 'muted', `Open an APESpace meeting (${origins.map(o => new URL(o).host).join(', ')}) to check its code.`));

        return;
    }
    const files = state.files ?? [];
    const count = s => files.filter(f => f.status === s).length;
    const verdict = {
        ok: [ 'ok', `✓ This meeting runs a signed APESpace release` ],
        fail: [ 'bad', state.unknownBundle ? '✗ This meeting runs an app that is not in any published release'
            : '✗ This meeting runs code that does not match the signed release' ],
        pending: [ 'muted', state.error ?? 'Checking…' ]
    }[state.verdict];

    box.append(el('p', `verdict ${verdict[0]}`, verdict[1]));

    if (state.release) {
        box.append(el('div', 'mono', `Release ${state.release.id}`));
        const list = el('ul');

        for (const b of state.release.builds) {
            const li = el('li', b.verified ? 'ok' : 'bad', b.verified
                ? `Signed by the official build: ${b.source.branch} @ ${b.source.commit.slice(0, 7)}, ${new Date(b.builtAt).toLocaleString()} `
                : `A build record does not verify: ${b.error}`);

            if (b.verified) {
                const a = Object.assign(el('a', '', `(public log #${b.logIndex})`),
                    { href: `https://search.sigstore.dev/?logIndex=${b.logIndex}`, target: '_blank' });

                li.append(a);
            }
            list.append(li);
        }
        box.append(list);
    }

    const summary = el('ul');

    summary.append(el('li', '', `${count('ok')} of ${files.length} scripts, WebAssembly modules and stylesheets this meeting loaded match the signed release`));
    for (const f of files.filter(x => [ 'mismatch', 'unpublished', 'error' ].includes(x.status))) {
        summary.append(el('li', 'bad mono', `${f.path}: ${{ mismatch: 'differs from the release',
            unpublished: 'not part of the release', error: 'could not be checked' }[f.status]}`));
    }
    summary.append(el('li', 'muted', 'The meeting page and config.js are generated by the server for its own deployment, so they are not compared.'));
    box.append(summary);
}

chrome.tabs.query({ active: true, currentWindow: true }, ([ tab ]) => {
    chrome.runtime.sendMessage({ type: 'code-status', tabId: tab?.id }, state => {
        chrome.runtime.sendMessage({ type: 'get' }, status => showCode(state, status.origins));
    });
});

// ------------------------------------------------------------ inspector

function showInspector({ on, allSites }) {
    $('on').checked = on;
    $('all').checked = allSites;
    $('all').disabled = !on;
}

chrome.runtime.sendMessage({ type: 'get' }, showInspector);
$('on').onchange = () => chrome.runtime.sendMessage({ type: 'set', on: $('on').checked }, showInspector);

// Must run in the click handler: Chrome only asks for a permission on a user action.
$('all').onchange = async () => {
    $('all').checked ? await chrome.permissions.request(ALL_SITES) : await chrome.permissions.remove(ALL_SITES);
    chrome.runtime.sendMessage({ type: 'get' }, showInspector);
};
$('viewer').onclick = () => chrome.tabs.create({ url: 'inspector/viewer.html' });
